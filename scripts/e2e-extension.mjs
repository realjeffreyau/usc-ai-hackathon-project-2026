// Exercises the actual unpacked extension against fictional WebReg markup. Never signs in or registers.
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { browserTools, chromePath, storageState } from './browser-support.mjs';
import { coursebinHtml, coursesListHtml } from '../tests/mock-coursebin.mjs';
import { makePdf, fictionalAudit } from '../tests/pdf-fixture.mjs';
const { chromium } = browserTools();
const profile = mkdtempSync(join(tmpdir(), 'troyplan-extension-'));
const extension = fileURLToPath(new URL('../extension/', import.meta.url));
const context = await chromium.launchPersistentContext(profile, {
  executablePath: chromePath(), headless: false, viewport: { width: 1280, height: 900 },
  args: ['--headless=new', `--disable-extensions-except=${extension}`, `--load-extension=${extension}`, '--no-first-run'],
});
await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'https://webreg.usc.edu' });
await context.route('https://webreg.usc.edu/**', route => route.fulfill({ status: 200, contentType: 'text/html', body: new URL(route.request().url()).pathname === '/Courses' ? coursesListHtml() : coursebinHtml() }));
const requests = [], problems = [], failures = [];
context.on('request', r => requests.push({ url: r.url(), method: r.method(), body: r.postData() }));
context.on('response', r => { if (r.status() >= 400) failures.push(`${r.status()} ${r.url()}`); });
let count = 0;
const ok = text => console.log(`PASS ${++count}: ${text}`);
const page = await context.newPage();
page.setDefaultTimeout(10000);
page.on('pageerror', e => problems.push(e.message));
page.on('console', m => { if (['error', 'warning'].includes(m.type()) && !/Indexing all PDF objects|standardFontDataUrl|Unable to create a text session because the service is not running/.test(m.text())) problems.push(m.text()); });
const waitText = (selector, text) => page.locator(selector).filter({ hasText: text }).waitFor();
try {
  await page.goto('https://webreg.usc.edu/CourseBin');
  await page.locator('.launcher').click();
  await page.locator('[data-fk=read-bin]').click();
  await waitText('#tp-view-plan', /registered/);
  await page.locator('#tp-prompt').fill('No classes before 10 am, at most 16 units');
  await page.locator('[data-fk=build]').click();
  await waitText('#tp-view-plan', /10002/);
  await waitText('#tp-view-plan', /built-in rules/);
  assert.ok(await page.locator('[data-trojan-planner=recommended]').count() >= 2);
  assert.deepEqual(await page.evaluate(() => window.__clicks), []);
  ok('Live myCourseBin read and deterministic plan, with no host-page control clicks');
  await page.locator('[data-fk=copy]').click();
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /10002/);
  ok('explicit clipboard action copies recommended live section numbers');
  assert.deepEqual(await storageState(page), { local: 0, session: 0, cookies: '', databases: [], caches: [] });
  await page.goto('https://webreg.usc.edu/Courses');
  await page.locator('.launcher').click();
  await page.locator('#tp-tab-plan').click();
  await page.locator('[data-fk=sub-ge]').click();
  await waitText('#tp-view-plan', /not read on this page/);
  await page.getByRole('button', { name: 'Read this page', exact: true }).click();
  await page.locator('.geres').first().waitFor();
  assert.equal(await page.locator('.geres').count(), 2);
  assert.match(await page.locator('.geres').first().innerText(), /Rating not loaded/);
  ok('navigation clears registered data and warns about incomplete cross-page fit checks');
  await page.locator('[data-fk=mode-toggle]').click();
  await waitText('#tp-view-progress', /fictional profile/);
  await page.locator('[data-fk="find-GE-B_Humanistic_Inquiry"]').click();
  await page.locator('.geres').first().waitFor();
  assert.match(await page.locator('.geres').first().innerText(), /Sample rating/);
  assert.equal(await page.getByRole('tab').filter({ hasText: 'Four-Year Plan' }).count(), 0);
  ok('Demo mode loads the fictional audit and bundled catalogue in the two-tab drawer');
  await page.locator('[data-fk=close]').click();
  await page.locator('.launcher').click();
  assert.ok(await page.locator('.geres').count() > 0);
  ok('closing and reopening preserves in-memory demo state');
  await page.locator('#tp-tab-progress').click();
  await page.getByRole('button', { name: 'Switch', exact: true }).click();
  await page.getByRole('button', { name: 'Import STARS report instead', exact: true }).click();
  await page.locator('#tp-file').setInputFiles({ name: 'fictional-audit.pdf', mimeType: 'application/pdf', buffer: makePdf(fictionalAudit) });
  await waitText('#tp-view-progress', /Imported audit/);
  await page.locator('[data-fk=confirm]').waitFor();
  assert.deepEqual(await storageState(page), { local: 0, session: 0, cookies: '', databases: [], caches: [] });
  ok('fictional PDF import stays in memory and requires credit confirmation');
  const extensionUrl = requests.find(r => r.url.startsWith('chrome-extension://'))?.url;
  assert.ok(extensionUrl);
  const demo = await context.newPage();
  demo.on('pageerror', e => problems.push(e.message));
  await demo.goto(new URL('/demo.html', extensionUrl).href);
  await demo.locator('#tp-view-progress').filter({ hasText: 'fictional profile' }).waitFor();
  ok('bundled extension rehearsal page opens without USC credentials');
  assert.ok(requests.every(r => (r.url.startsWith('https://webreg.usc.edu/') || r.url.startsWith('chrome-extension://')) && r.method === 'GET' && !r.body && !r.url.includes('FICTIONAL-MARKER') && !r.url.includes('fictional-audit')));
  assert.deepEqual(await page.evaluate(() => window.__clicks), []);
  assert.deepEqual(failures, []); assert.deepEqual(problems, []);
  ok('only mocked WebReg and bundled assets requested; no private-data requests, storage, or registration clicks');
  console.log(`${count} extension browser checks passed.`);
} finally { await context.close(); rmSync(profile, { recursive: true, force: true }); }
