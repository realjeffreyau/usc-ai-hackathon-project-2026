// Browser test of the TroyPlan website (dist/). Serves it locally, then walks: three tabs, major and minor from the bundled
// USC Catalogue snapshot, the Four-Year Plan board, the open-GE-slot flow, one shared plan, phone layout and keyboard use.
// Needs Playwright (not a project dependency): PLAYWRIGHT_CORE=/path/to/playwright-core, optional CHROMIUM_PATH.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { mkdirSync } from 'node:fs';
import { start } from './serve.mjs';

const require = createRequire(import.meta.url);
let chromium;
for (const name of [process.env.PLAYWRIGHT_CORE, join(homedir(), '.npm-global/lib/node_modules/@playwright/cli/node_modules/playwright-core'), 'playwright-core', 'playwright'].filter(Boolean)) { try { ({ chromium } = require(name)); break; } catch { /* next */ } }
if (!chromium) throw new Error('playwright-core not found. Set PLAYWRIGHT_CORE=/path/to/playwright-core');
const shots = process.env.SHOTS_DIR;
if (shots) mkdirSync(shots, { recursive: true });
const defaultBrowser = join(homedir(), 'Library/Caches/ms-playwright/chromium_headless_shell-1243/chrome-headless-shell-mac-arm64/chrome-headless-shell');

let step = 0;
const ok = message => console.log(`  ✓ ${String(++step).padStart(2, '0')} ${message}`);
const server = process.env.QA_BASE_URL ? null : await start(0);
const origin = process.env.QA_BASE_URL ? new URL(process.env.QA_BASE_URL).origin : `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || defaultBrowser });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
const requests = [], problems = [];
context.on('request', request => requests.push({ url: request.url(), method: request.method(), body: request.postData() }));
const page = await context.newPage();
page.on('console', message => { if (['error', 'warning'].includes(message.type())) problems.push(`${message.type()}: ${message.text()}`); });
page.on('pageerror', error => problems.push('pageerror: ' + error.message));
const shot = async name => { if (shots) await page.screenshot({ path: join(shots, name + '.png'), fullPage: true }); };
const tab = id => page.locator(`#tp-tab-${id}`);
const key = k => page.evaluate(x => document.getElementById('trojan-planner-host').shadowRoot.activeElement?.getAttribute('data-fk'), k);
const termBox = label => page.locator(`.bterm:has(h4#bt-${label.replace(/[^\w-]/g, '_')})`);
const unitsOf = async label => Number((await termBox(label).locator('.bt-units').innerText()).match(/[\d.]+/)[0]);

try {
  console.log('Website shell');
  await page.goto(origin + '/');
  await page.waitForSelector('.tab');
  assert.equal(await page.title(), 'TroyPlan');
  assert.deepEqual(await page.locator('.tabs .tab').allInnerTexts(), ['Degree Progress', 'Four-Year Plan', 'Plan Semester']);
  assert.equal(await tab('progress').getAttribute('aria-selected'), 'true', 'Degree Progress is the first screen');
  await page.waitForSelector('.programs summary:has-text("Biomedical Engineering (BS)")');
  assert.equal(await page.locator('.datapill').count(), 1);
  assert.match(await page.locator('.datapill').innerText(), /Demo data/);
  assert.equal(await page.locator('.head a.headlink, .head [data-fk=close]').count(), 0, 'no drawer-only controls on the website');
  ok('website opens on Degree Progress with three tabs (Degree Progress, Four-Year Plan, Plan Semester) and a single "Demo data" label');

  console.log('Major and minor from the USC Catalogue');
  await page.locator('.programs summary').click();
  const majors = await page.locator('#tp-list-major option').count();
  const minors = await page.locator('#tp-list-minor option').count();
  assert.ok(majors >= 150 && minors >= 200, `${majors} majors, ${minors} minors`);
  assert.match(await page.locator('.programs').innerText(), /2026-2027 USC Catalogue/);
  assert.equal(await page.locator('.programs a[href^="https://catalogue.usc.edu/"]').count(), 1);
  await page.locator('#tp-major').fill('Philosophy (BA)');
  await page.locator('#tp-major').press('Tab');
  await page.waitForFunction(() => /Philosophy \(BA\)/.test(document.getElementById('trojan-planner-host').shadowRoot.querySelector('.programs summary').textContent));
  assert.match(await page.locator('.toast').innerText(), /Philosophy \(BA\) requirements loaded from the 2026-2027 USC Catalogue\./);
  const phil = await page.locator('#tp-req-h').locator('xpath=..').innerText();
  assert.match(phil, /Philosophy/i);
  assert.ok(!/Math Requirement/.test(phil), 'the Biomedical Engineering rows are gone');
  await page.locator('#tp-minor').fill('Philosophy Minor');
  await page.locator('#tp-minor').press('Tab');
  await page.waitForFunction(() => /Philosophy Minor/.test(document.getElementById('trojan-planner-host').shadowRoot.querySelector('.programs summary').textContent));
  assert.match(await page.locator('#tp-req-h').locator('xpath=..').innerText(), /Minor · /);
  await page.locator('#tp-major').fill('Biomedical Engineering (BS)');
  await page.locator('#tp-major').press('Tab');
  await page.locator('[aria-label="Clear minor"]').click();
  await page.waitForFunction(() => /^Program: Biomedical Engineering \(BS\)$/.test(document.getElementById('trojan-planner-host').shadowRoot.querySelector('.programs summary').textContent.trim()));
  const bme = await page.locator('#tp-req-h').locator('xpath=..').innerText();
  assert.match(bme, /Math Requirement/);
  assert.match(bme, /GE-B Humanistic Inquiry/);
  assert.ok(!/Minor · /.test(bme));
  ok('choose a major and a minor from the catalogue snapshot: requirement groups (and "Minor ·" rows) replace each other with real course lists; clearing the minor removes them');
  await shot('s01-progress');

  console.log('Four-Year Plan board');
  await tab('four').click();
  await page.waitForSelector('.byear');
  assert.equal(await page.evaluate(() => location.hash), '#four-year');
  const top = await page.locator('.topbar').innerText();
  assert.match(top, /Biomedical Engineering \(BS\)/);
  assert.match(top, /Catalog year 2026-2027/);
  assert.match(top, /Target graduation (Fall|Spring) 20\d\d/);
  assert.match(top, /Earned\s*62 units/);
  assert.match(top, /Planned\s*8 units this term/);
  assert.match(top, /Open\s*\d+ requirements/);
  assert.equal(await page.locator('.byear').count() >= 4, true);
  assert.ok((await page.locator('.bt-units').allInnerTexts()).every(t => /\d+ units/.test(t)), 'a unit total above each semester');
  assert.equal(await page.locator('.bterm.current').count(), 1);
  assert.match(await page.locator('.bterm.current').innerText(), /Fall[\s\S]*Current term/);
  assert.match(await page.locator('.bterm.current').getAttribute('class'), /current/);
  assert.equal(await page.evaluate(() => getComputedStyle(document.getElementById('trojan-planner-host').shadowRoot.querySelector('.bterm.current')).borderTopWidth), '2px', 'visible outline');
  const labels = await page.locator('.bcard .bc-foot .tag').allInnerTexts();
  for (const label of ['Completed', 'In progress', 'Registered', 'Estimate', 'Open']) assert.ok(labels.includes(label), `status label "${label}" is shown as text`);
  const sample = await page.locator('.bcard:has-text("BME 210")').first().innerText();
  assert.match(sample, /BME 210/);
  assert.match(sample, /Biomedical Computer Simulation Methods/);
  assert.match(sample, /4 units/);
  assert.match(sample, /Major Requirements · Biomedical Engineering/);
  assert.match(sample, /Estimate/);
  ok('top bar (program, catalog year, target graduation, earned / planned / open), year-by-year Fall and Spring columns with unit totals, outlined current term, text status labels, cards with code, title, units and requirement');
  await shot('s02-four');

  console.log('Card details and moving a course');
  await page.locator('.bcard:has-text("BME 445BL")').click();
  await page.waitForSelector('#bd-head');
  assert.equal(await key(), 'bd-head', 'focus moves to the details');
  const detail = await page.locator('.bdetail').innerText();
  assert.match(detail, /BME 445BL/);
  assert.match(detail, /Prerequisites:\s*BME 445A/);
  assert.match(detail, /Move to another term/);
  assert.equal(await page.locator('.board-issue, .bcard.issue').count(), 0, 'no issues by default');
  const target = await page.locator('#bd-term option').first().innerText();
  await page.locator('#bd-term').selectOption(target);
  await page.locator('.bdetail button:has-text("Move")').click();
  await page.waitForFunction(() => document.getElementById('trojan-planner-host').shadowRoot.querySelectorAll('.bcard.issue').length > 0);
  assert.match(await page.locator('.toast').innerText(), /BME 445BL moved to .*Prerequisite issue: Needs BME 445A in an earlier term/);
  assert.match(await page.locator('.bcard.issue').first().innerText(), /BME 445BL[\s\S]*Prerequisite issue/);
  assert.match(await page.locator('section[aria-label="Prerequisite issues"]').innerText(), /1 prerequisite issue/);
  assert.match(await key(), /^bc-BME-445BL?_later$/, 'focus returns to the moved card');
  ok('a card opens its prerequisites and a "Move to another term" action; moving a course ahead of its prerequisite flags it on the board (text label, summary count, announcement)');
  await shot('s03-issue');
  await page.locator('.bcard.issue').first().click();
  const later = await page.locator('#bd-term option').last().innerText();
  await page.locator('#bd-term').selectOption(later);
  await page.locator('.bdetail button:has-text("Move")').click();
  await page.waitForFunction(() => document.getElementById('trojan-planner-host').shadowRoot.querySelectorAll('.bcard.issue').length === 0);
  ok('moving it later clears the issue');

  console.log('Drag tiles between terms');
  await page.setViewportSize({ width: 1400, height: 2000 });
  await tab('four').click();
  await page.waitForSelector('.byear');
  const inTerm = async (label, code) => termBox(label).locator(`.bcard:has-text("${code}")`).count();
  assert.equal(await inTerm('Spring 2028', 'BME 210'), 1, 'starts in Spring 2028');
  const tile = page.locator('.bcard:has-text("BME 210")');
  const dest = termBox('Fall 2028');
  const a = await tile.boundingBox(), b = await dest.boundingBox();
  await page.mouse.move(a.x + 30, a.y + 20); await page.mouse.down();
  await page.mouse.move(a.x + 60, a.y + 50, { steps: 4 });
  assert.equal(await page.locator('.ghost').count(), 1, 'a tile follows the pointer');
  assert.ok(await page.locator('.bterm.drop-ok').count() >= 3 && await page.locator('.bterm.drop-no').count() >= 4, 'valid and invalid terms are marked');
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 8 });
  assert.equal(await termBox('Fall 2028').getAttribute('class').then(c => c.includes('drop-over')), true, 'the target term lights up');
  await page.mouse.up();
  await page.waitForFunction(() => !document.getElementById('trojan-planner-host').shadowRoot.querySelector('.ghost'));
  assert.equal(await inTerm('Fall 2028', 'BME 210'), 1, 'dropped into Fall 2028');
  assert.match(await page.locator('.toast').innerText(), /BME 210 moved to Fall 2028\./);
  assert.ok(!/BME 210/.test(await page.locator('#bd-head').innerText().catch(() => '')), 'a drag does not open the details');
  await shot('s03b-dragged');
  // Keyboard alternative.
  await page.locator('.bcard:has-text("BME 210")').focus();
  await page.keyboard.press('Alt+ArrowLeft');
  await page.waitForFunction(() => /BME 210 moved to Spring 2028/.test(document.getElementById('trojan-planner-host').shadowRoot.querySelector('.toast').textContent));
  assert.equal(await inTerm('Spring 2028', 'BME 210'), 1);
  // Completed tiles are not draggable.
  const done = page.locator('.bcard.completed').first(); const d = await done.boundingBox();
  await page.mouse.move(d.x + 20, d.y + 20); await page.mouse.down(); await page.mouse.move(d.x + 80, d.y + 90, { steps: 4 });
  assert.equal(await page.locator('.ghost').count(), 0); await page.mouse.up();
  ok('press-and-drag a dashed tile: it lifts, valid terms light up, dropping moves it and announces it; Alt+Left/Right does the same by keyboard; completed tiles stay put');

  console.log('Open GE slot to GE Finder and back (one shared plan)');
  const springBefore = await unitsOf('Spring 2027');
  const slot = page.locator('.bcard.open:has-text("GE-B")');
  assert.match(await slot.innerText(), /GE-B[\s\S]*Choose a course/);
  assert.match(await termBox('Spring 2027').innerText(), /GE-B/);
  await slot.click();
  assert.match(await page.locator('.bdetail').innerText(), /Open/);
  await page.locator('[data-fk=find-slot]').click();
  await page.waitForSelector('.geres');
  assert.equal(await tab('plan').getAttribute('aria-selected'), 'true');
  assert.equal(await page.locator('[data-fk=sub-ge]').getAttribute('aria-selected'), 'true');
  assert.equal(await page.locator('[data-fk=ge-cat]').inputValue(), 'GE-B', 'category carried over');
  assert.match(await page.locator('.geres').first().innerText(), /Stories That Shaped Cities/);
  assert.match(await page.locator('.geres').first().innerText(), /Sample rating/);
  await page.locator('.geres').first().locator('button:has-text("Add to plan")').click();
  await page.waitForSelector('.plancard:has-text("HMNT 215")');
  assert.match(await page.locator('#tp-sum-h').innerText(), /Spring 2027 · 12 units/);
  await tab('four').click();
  await page.waitForSelector('.byear');
  assert.equal(await page.locator('.bcard.open:has-text("GE-B")').count(), 0, 'the slot is filled');
  const filled = page.locator('.bcard:has-text("HMNT 215")');
  assert.match(await filled.innerText(), /Stories That Shaped Cities[\s\S]*Planned/);
  assert.equal(await unitsOf('Spring 2027'), springBefore, 'the open slot already counted its 4 units; filling it keeps the total');
  assert.match(await page.locator('.topbar').innerText(), /Planned\s*12 units this term/, 'planned units updated');
  await filled.click();
  const planDetail = await page.locator('.bdetail').innerText();
  assert.match(planDetail, /Sections for Spring 2027/i);
  assert.match(planDetail, /Lecture\s*98215\s*Mon\/Wed 4:30 PM - 5:45 PM/);
  assert.match(planDetail, /Ellis Marlowe/);
  assert.match(planDetail, /4\.8/);
  await tab('progress').click();
  assert.match(await page.locator('.req:has-text("GE-B Humanistic Inquiry")').innerText(), /Planned/);
  ok('click an open GE slot, compare eligible courses (category and term already selected), add one: it fills the slot in the grid, the term\'s units update, details show times and the instructor rating, and Degree Progress shows Planned');
  await shot('s04-filled');

  console.log('A GE slot in a term without sections');
  await tab('four').click();
  await page.waitForSelector('.byear');
  await page.locator('.bcard.open:has-text("GE-C")').click();
  await page.locator('[data-fk=find-slot]').click();
  await page.waitForSelector('#tp-gco-h');
  assert.match(await page.locator('#tp-gco-h').locator('xpath=..').innerText(), /Sections for Fall 2027 are not published yet/);
  const fall = await unitsOf('Fall 2027').catch(() => null);
  await page.locator('button:has-text("Choose for Fall 2027")').first().click();
  await page.waitForSelector('.byear');
  assert.match(await termBox('Fall 2027').innerText(), /Planned/);
  assert.equal(await page.locator('.bcard.open:has-text("GE-C")').count(), 0);
  assert.ok(fall !== null);
  ok('a slot in a later term says sections are not published, lets you pick the course now, and the grid shows it in that term');

  console.log('Phone layout and keyboard');
  await page.setViewportSize({ width: 390, height: 900 });
  await page.waitForTimeout(300);
  assert.ok(await page.locator('.yearsel').isVisible(), 'year selector on phones');
  assert.equal(await page.locator('.byear.sel').count(), 1);
  assert.equal(await page.evaluate(() => [...document.getElementById('trojan-planner-host').shadowRoot.querySelectorAll('.byear')].filter(el => el.offsetParent !== null).length), 1, 'one year at a time');
  const cols = await page.evaluate(() => getComputedStyle(document.getElementById('trojan-planner-host').shadowRoot.querySelector('.byear.sel .terms')).gridTemplateColumns.split(' ').length);
  assert.equal(cols, 1, 'Fall and Spring stack on phones');
  await page.locator('.yearsel button').nth(2).click();
  assert.equal(await page.evaluate(() => [...document.getElementById('trojan-planner-host').shadowRoot.querySelectorAll('.byear')].filter(el => el.offsetParent !== null).length), 1);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 1, true, 'no horizontal page scroll');
  await shot('s05-phone');
  await page.setViewportSize({ width: 1280, height: 900 });
  assert.equal(await page.evaluate(() => [...document.getElementById('trojan-planner-host').shadowRoot.querySelectorAll('.byear')].filter(el => el.offsetParent !== null).length) >= 4, true, 'all years show side by side on wide screens');
  await tab('four').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await tab('plan').getAttribute('aria-selected'), 'true');
  await page.keyboard.press('ArrowLeft');
  await page.keyboard.press('ArrowLeft');
  assert.equal(await tab('progress').getAttribute('aria-selected'), 'true');
  await tab('four').click();
  await page.locator('.bcard').first().focus();
  await page.keyboard.press('Enter');
  await page.waitForSelector('#bd-head');
  assert.equal(await key(), 'bd-head');
  ok('phone: one year at a time with a year selector, Fall and Spring stacked, no horizontal scroll; wide: all years; arrow keys switch tabs; Enter on a focused card opens its details');

  console.log('Routing and safety');
  await page.goto(origin + '/#four-year');
  await page.waitForSelector('.byear');
  assert.equal(await tab('four').getAttribute('aria-selected'), 'true', 'deep link opens the Four-Year Plan');
  const outside = requests.filter(r => !r.url.startsWith(origin + '/') && !r.url.startsWith('data:'));
  assert.deepEqual(outside.map(r => r.url), []);
  assert.ok(requests.every(r => r.method === 'GET' && !r.body));
  const stores = await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length, cookie: document.cookie }));
  assert.deepEqual(stores, { local: 0, session: 0, cookie: '' });
  ok(`#four-year opens the board; ${requests.length} requests, all GET to this origin; no localStorage, sessionStorage or cookies`);
  assert.deepEqual(problems, [], 'no console errors or CSP violations');
  ok('no console errors, warnings or CSP violations');
  console.log('\nAll website checks passed.');
} catch (error) {
  console.error('\nSITE E2E FAILED:', error.message);
  if (problems.length) console.error('Browser problems:\n' + problems.join('\n'));
  process.exitCode = 1;
} finally {
  await browser.close();
  server?.close();
}
